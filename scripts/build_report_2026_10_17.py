    rows.append(['بولينجر (20، 2)', f"{f(a, d['bb_dn'])} – {f(a, d['bb_up'])}", f"\u2066%b = {pb:.2f}\u2069 ← {bm}"])
    iv = d['iv_annual']
    ivp = SNAP[a].get('ivp_52w')
    ivm = f"تقلّب ضمني سنوي {100*iv:.1f}%"
    if ivp is not None:
        ivm += f" — مئين 52 أسبوعاً ≈ {100*ivp:.0f}% ({'رخيص نسبياً' if ivp < 0.3 else 'مرتفع نسبياً' if ivp > 0.7 else 'متوسط'})"
