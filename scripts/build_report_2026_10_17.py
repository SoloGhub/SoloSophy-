# ---------------------------------------------------------------- analogs (descriptive, from IBKR daily bars)
def weekly_series(asset):
    r = json.load(open(ROOT / f'data/raw/2026-10-17/daily/{asset.lower()}_daily_long.json'))['response']
    rows = []
    for i, t in enumerate(r['time']):
        o, h, lo, c, v = r['open'][i], r['high'][i], r['low'][i], r['close'][i], r['volume'][i]
        ok = lo <= min(o, c) + 1e-9 and h >= max(o, c) - 1e-9 and v > 0
        d = datetime.datetime.fromisoformat(t.replace('Z', '+00:00'))
        if asset != 'SOXL':
            d = d + datetime.timedelta(hours=4)   # futures bar stamped at session open (22:00Z) -> session date
        rows.append((d.date(), c, ok))
    k = len(rows)
    while k > 0 and rows[k - 1][2]:
        k -= 1
    rows = rows[k:]
    wk = {}
    for d, c, _ in rows:
        iso = d.isocalendar()
        wk[(iso[0], iso[1])] = (d, c)
    keys = sorted(wk)
    return [wk[x][0] for x in keys], [wk[x][1] for x in keys]


def analog(asset, cond, label):
    dt, cl = weekly_series(asset)
    ret = [None] + [100 * (cl[i] / cl[i - 1] - 1) for i in range(1, len(cl))]
    hits = []
    for i in range(1, len(cl) - 1):          # exclude the current week (last)
        if cond(ret[i]):
            hits.append(dict(week=str(dt[i]), ret=round(ret[i], 2), next=round(ret[i + 1], 2)))
    nxt = [h['next'] for h in hits]
    res = dict(asset=asset, label=label, sample_weeks=len(cl) - 1, period=f"{dt[0]} → {dt[-1]}", n=len(hits), cases=hits[-8:])
    if nxt:
        s = sorted(nxt)
        res.update(next_up_share=round(100 * sum(1 for x in nxt if x > 0) / len(nxt)), next_median=round(s[len(s) // 2], 2),
                   next_min=round(min(nxt), 2), next_max=round(max(nxt), 2))
    return res


