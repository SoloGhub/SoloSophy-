def ladder(asset, why):
    d = L[asset]
    c, s = d['close'], d['week_1sigma']
    b = [c + s, c + 0.3 * s, c - 0.3 * s, c - s]
    w = LADDER[asset]
    rng = [(f"فوق {f(asset, b[0])}", None, b[0]), (f"{f(asset, b[1])} – {f(asset, b[0])}", b[1], b[0]),
           (f"{f(asset, b[2])} – {f(asset, b[1])}", b[2], b[1]), (f"{f(asset, b[3])} – {f(asset, b[2])}", b[3], b[2]),
           (f"تحت {f(asset, b[3])}", None, b[3])]
    items = []
    for i in range(5):
        items.append(dict(key=LADDER_KEYS[i], name=LADDER_NAMES[i], weight=w[i], base=BASE[i], tilt=w[i] - BASE[i],
                          range=rng[i][0], why=why[i]))
    return dict(items=items, up_total=w[0] + w[1], range_total=w[2], down_total=w[3] + w[4],
                sigma=round(s, SPEC[asset]['dec'] + 1), iv=round(100 * d['iv_annual'], 1),
                one_sigma=[round(c - s, SPEC[asset]['dec']), round(c + s, SPEC[asset]['dec'])],
                two_sigma=[round(c - 2 * s, SPEC[asset]['dec']), round(c + 2 * s, SPEC[asset]['dec'])],
                horizon='أسبوع 19–23 أكتوبر 2026 (إغلاق الجمعة)',
                ntz=[round(b[2], SPEC[asset]['dec']), round(b[1], SPEC[asset]['dec'])])


